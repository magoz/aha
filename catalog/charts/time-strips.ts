/**
 * time-strips component definition. Stacked rows share one time axis; each
 * row keeps its own small scale.
 */

function decodeRequest(request: JsonRenderRequest): Effect.Effect<string, BlockDecodeError> {
  return Schema.decodeUnknownEffect(TimeStripsSchema)(request.json).pipe(
    Effect.mapError(
      (parseError) =>
        new BlockDecodeError({
          blockIndex: request.blockIndex,
          component: 'time-strips',
          path: firstIssuePath(parseError.issue),
          detail: formatIssueDetail(parseError.issue)
        })
    ),
    Effect.flatMap((decoded) => {
      if (decoded.rows.length === 0) {
        return Effect.fail(
          new BlockDecodeError({
            blockIndex: request.blockIndex,
            component: 'time-strips',
            path: 'rows',
            detail: 'expected at least one row'
          })
        )
      }

      return Effect.succeed(
        renderTimeStrips(decoded, { width: request.width, idPrefix: request.idPrefix })
      )
    })
  )
}

